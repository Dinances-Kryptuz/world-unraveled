import type { ClassId } from '../gameData/classStats';
import type { ResourcePool, ResourceType } from './types';

// Which resource pools a class's combatant starts combat with. A class can
// have more than one (Paladin: Mana + Holy Power) — Phase 1 abilities only
// spend Holy Power, but Mana is tracked now so mana-spending Paladin
// abilities in a later phase don't need a resource-model change.
// flatManaBonus: Enchanting overhaul's flat Mana enchants (Minor/Lesser/
// .../Ember Mana) — see maxHp()'s matching flatHpBonus doc comment in
// combatFormulas.ts for why this is a literal flat addend, not a stat-point
// conversion.
export function initialResources(
  cls: ClassId,
  level: number,
  intStat: number,
  flatManaBonus = 0
): Partial<Record<ResourceType, ResourcePool>> {
  switch (cls) {
    case 'warrior':
      return { rage: { current: 0, max: 100 } };
    case 'priest': {
      const max = manaMax(level, intStat, flatManaBonus);
      return { mana: { current: max, max } };
    }
    case 'paladin': {
      const max = manaMax(level, intStat, flatManaBonus);
      return {
        mana: { current: max, max },
        holyPower: { current: 0, max: 5 },
      };
    }
    case 'mage': {
      const max = manaMax(level, intStat, flatManaBonus);
      return { mana: { current: max, max } };
    }
    // Rogue's V1 kit (engine.ts's applyCripplingPoisonDebuff/
    // applyDeadlyPoisonStack) spends no resource at all — no Energy system
    // modeled yet, same "for now" minimal scope as the rest of its kit.
    case 'rogue':
      return {};
  }
}

function manaMax(level: number, intStat: number, flatManaBonus = 0): number {
  return Math.round(50 + level * 10 + intStat * 2 + flatManaBonus);
}

// Which resource types a class's combatant ever has, in the same order
// initialResources() creates them — used by the Combat Setup screen to only
// offer resource conditions ("if my Mana is below...") that actually apply.
export function resourcesForClass(cls: ClassId): ResourceType[] {
  switch (cls) {
    case 'warrior':
      return ['rage'];
    case 'priest':
      return ['mana'];
    case 'paladin':
      return ['mana', 'holyPower'];
    case 'mage':
      return ['mana'];
    case 'rogue':
      return [];
  }
}

// Mana regenerates a small percentage of its max every second, in or out of
// combat, matching classic MMO baseline regen. Holy Power has no passive
// regen; it's only generated by abilities. Rage has a small passive trickle
// (useAbility in engine.ts adds the much larger on-hit/on-hit-taken gains on
// top of this) so a Warrior who opens on cooldown still slowly refills
// instead of sitting at 0 waiting to be hit.
const MANA_REGEN_PCT_PER_SECOND = 0.02;
const RAGE_REGEN_PER_SECOND = 1;

export function regenResources(
  resources: Partial<Record<ResourceType, ResourcePool>>,
  deltaSeconds: number,
  // SPI's mana-regen-rate bonus (Attribute/Specialization overhaul — see
  // combatFormulas.ts's manaRegenMultiplier). Defaults to 1 (no bonus) so
  // every caller that hasn't been updated to pass a combatant's profile
  // value behaves exactly as before this param existed.
  manaRegenMult = 1
): void {
  const mana = resources.mana;
  if (mana) {
    mana.current = Math.min(mana.max, mana.current + mana.max * MANA_REGEN_PCT_PER_SECOND * manaRegenMult * deltaSeconds);
  }
  const rage = resources.rage;
  if (rage) {
    rage.current = Math.min(rage.max, rage.current + RAGE_REGEN_PER_SECOND * deltaSeconds);
  }
}

export function canAfford(resources: Partial<Record<ResourceType, ResourcePool>>, type: ResourceType | undefined, cost: number | undefined): boolean {
  if (!type || !cost) return true;
  const pool = resources[type];
  return !!pool && pool.current >= cost;
}

export function spend(resources: Partial<Record<ResourceType, ResourcePool>>, type: ResourceType | undefined, cost: number | undefined): void {
  if (!type || !cost) return;
  const pool = resources[type];
  if (pool) pool.current = Math.max(0, pool.current - cost);
}

export function gain(resources: Partial<Record<ResourceType, ResourcePool>>, type: ResourceType | undefined, amount: number | undefined): void {
  if (!type || !amount) return;
  const pool = resources[type];
  if (pool) pool.current = Math.min(pool.max, pool.current + amount);
}
