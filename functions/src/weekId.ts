// ISO-8601 week identifier ("2026-W42") — shared convention between the
// client (src/gameData/guildContracts.ts, display-only) and here (the only
// place that actually DECIDES which week a contract belongs to). Weeks
// start Monday and the year used is the ISO week-year (the year that owns
// the week's Thursday), not necessarily the calendar year of `date`.
export function isoWeekId(date: Date): string {
  const d = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  const dayNum = (d.getUTCDay() + 6) % 7; // Monday = 0 .. Sunday = 6
  d.setUTCDate(d.getUTCDate() - dayNum + 3); // shift to this week's Thursday
  const isoYear = d.getUTCFullYear();
  const firstThursday = new Date(Date.UTC(isoYear, 0, 4));
  const firstDayNum = (firstThursday.getUTCDay() + 6) % 7;
  firstThursday.setUTCDate(firstThursday.getUTCDate() - firstDayNum + 3);
  const weekNum = 1 + Math.round((d.getTime() - firstThursday.getTime()) / (7 * 24 * 3600 * 1000));
  return `${isoYear}-W${String(weekNum).padStart(2, '0')}`;
}
